// Helper to get audio URLs with fallback
export const getSurahAudioUrl = (reciter, surahId) => {
  const padNumber = String(surahId).padStart(3, '0');
  
  // Primary URL from mp3quran server
  const primaryUrl = `${reciter.serverUrl}/${padNumber}.mp3`;
  
  // Fallback URL: if reciter has an Islamic Network CDN identifier, use high-speed 128kbps CDN
  let fallbackUrl = null;
  if (reciter.cdnIdentifier) {
    fallbackUrl = `https://cdn.islamic.network/quran/audio-surah/128/${reciter.cdnIdentifier}/${surahId}.mp3`;
  } else {
    fallbackUrl = `https://server8.mp3quran.net/afs/${padNumber}.mp3`; // Alafasy fallback
  }

  return { primaryUrl, fallbackUrl };
};

export const getReciterById = (id) => {
  return RECITERS_DATA.find((r) => r.id === id) || RECITERS_DATA[0];
};
